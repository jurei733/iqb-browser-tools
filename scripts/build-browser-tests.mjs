import {build} from 'vite';
import {cp,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
const out=resolve(process.argv[2]||'work/browser-tests');
await build({base:'/',build:{outDir:out,emptyOutDir:true,rollupOptions:{input:{browser:fileURLToPath(new URL('../tests/browser.html',import.meta.url)),app:fileURLToPath(new URL('../index.html',import.meta.url)),acceptance:fileURLToPath(new URL('../tests/acceptance.html',import.meta.url))}}}});
await mkdir(out+'/fixtures',{recursive:true});
await cp(new URL('../tests/fixtures/',import.meta.url),out+'/fixtures',{recursive:true});
execFileSync(process.execPath,['scripts/prepare-acceptance.mjs',out],{stdio:'inherit'});
console.log('Browser tests:',out+'/tests/browser.html');
